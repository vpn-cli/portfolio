import { chromium } from "playwright-core";

async function verifyAll() {
  const browser = await chromium.launch({ channel: "msedge", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });

  let css200 = false;
  page.on("response", (res) => {
    if (res.request().resourceType() === "stylesheet" && res.status() === 200) {
      css200 = true;
    }
  });

  console.log("Navigating to http://localhost:3000...");
  await page.goto("http://localhost:3000", { waitUntil: "networkidle" });
  await page.waitForTimeout(2000);

  console.log("CSS request returned 200:", css200);

  // Check Task 1: Contact card copy
  const contactText = await page.locator(".tile-contact").innerText();
  const hasHeading = contactText.includes("Let’s talk.") || contactText.includes("Let's talk.");
  const hasSubline = contactText.includes("Roles, collaborations, or a chat about backend systems or drawing.");
  console.log("Task 1 - Contact tile heading 'Let’s talk.':", hasHeading);
  console.log("Task 1 - Contact tile subline:", hasSubline);

  // Check Hero availability
  const heroText = await page.locator(".tile-intro").innerText();
  const hasHeroAvailability = heroText.includes("Open to SDE roles · Immediate availability");
  console.log("Task 1 - Hero 'Open to SDE roles · Immediate availability':", hasHeroAvailability);

  // Check Task 4: AppForge caption in Selected Work
  const appforgeCaption = await page.locator(".tile-projects").innerText();
  const hasAppForgeCaption = appforgeCaption.includes("Generated by AppForge from one prompt");
  console.log("Task 4 - AppForge caption visible:", hasAppForgeCaption);

  // Check Task 2: Byte Pat Counter
  const byteTile = page.locator(".tile-byte");
  const byteButton = byteTile.locator('div[role="button"][aria-label="Pat Byte"]');
  const hasByteButton = (await byteButton.count()) > 0;
  console.log("Task 2 - Byte button with aria-label='Pat Byte':", hasByteButton);

  const initialLabels = await byteTile.innerText();
  console.log("Task 2 - Initial Byte text:", initialLabels.replace(/\n/g, " | "));

  // Pat Byte 5 times with 450ms interval (> 400ms cooldown)
  console.log("Task 2 - Patting Byte 5 times with 450ms cooldown...");
  for (let i = 1; i <= 5; i++) {
    await byteButton.click();
    await page.waitForTimeout(450);
  }
  await page.waitForTimeout(1000);
  const after5Text = await byteTile.innerText();
  console.log("Task 2 - Byte text after 5 pats:", after5Text.replace(/\n/g, " | "));

  // Hammer Byte 50 times rapidly
  console.log("Task 2 - Hammering Byte 50 times rapidly to test rate limit...");
  let got429 = false;
  page.on("response", (res) => {
    if (res.url().includes("/api/pats") && res.status() === 429) {
      got429 = true;
    }
  });

  for (let i = 0; i < 50; i++) {
    // Fire rapid click events
    byteButton.click({ force: true }).catch(() => {});
    await page.waitForTimeout(20);
  }
  await page.waitForTimeout(2000);

  console.log("Task 2 - Rate limit 429 triggered on rapid hammering:", got429);
  const afterHammerText = await byteTile.innerText();
  console.log("Task 2 - Byte text after hammer:", afterHammerText.replace(/\n/g, " | "));
  console.log("Task 2 - UI healthy and visible after hammering:", await byteButton.isVisible());

  // Screenshot light and dark modes
  console.log("Capturing screenshots of homepage in light & dark...");
  await page.screenshot({ path: "shots/homepage-dark.png" });
  console.log("Saved shots/homepage-dark.png");

  // Toggle theme to light mode
  const themeBtn = page.locator('.tile-intro button[aria-label*="mode"]');
  await themeBtn.click();
  await page.waitForTimeout(1000);
  await page.screenshot({ path: "shots/homepage-light.png" });
  console.log("Saved shots/homepage-light.png");

  await browser.close();
  console.log("All automated verification steps finished successfully!");
}

verifyAll().catch((err) => {
  console.error("Verification error:", err);
  process.exit(1);
});
